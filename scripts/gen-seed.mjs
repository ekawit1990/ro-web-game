// Generates supabase/migrations/0002_seed.sql from src/data/gamedata.json,
// so the database rules always use the same numbers as the game client.
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync(new URL('../src/data/gamedata.json', import.meta.url), 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const lines = ['-- GENERATED by `npm run gen:seed` from src/data/gamedata.json. Do not edit by hand.', ''];

const shop = [...data.shop, ...data.weaponShop];
for (const [id, it] of Object.entries(data.items)) {
  const classes = it.classes ? `array[${it.classes.map(q).join(', ')}]` : 'null';
  lines.push(
    `insert into public.item_defs (id, type, price, classes, in_shop, weight) values (${q(id)}, ${q(it.type)}, ${it.price}, ${classes}, ${shop.includes(id)}, ${it.weight})` +
      ` on conflict (id) do update set type = excluded.type, price = excluded.price, classes = excluded.classes, in_shop = excluded.in_shop, weight = excluded.weight;`,
  );
}
lines.push('');
for (const [id, c] of Object.entries(data.classes)) {
  lines.push(
    `insert into public.class_defs (id, base_stats, start_weapon) values (${q(id)}, ${q(JSON.stringify(c.baseStats))}, ${q(c.startWeapon)})` +
      ` on conflict (id) do update set base_stats = excluded.base_stats, start_weapon = excluded.start_weapon;`,
  );
}
lines.push('');
for (const [id, m] of Object.entries(data.monsters)) {
  lines.push(
    `insert into public.monster_defs (id, level, exp, job_exp, zeny_min, zeny_max, drops) values (${q(id)}, ${m.level}, ${m.exp}, ${m.jobExp}, ${m.zeny[0]}, ${m.zeny[1]}, ${q(JSON.stringify(m.drops))})` +
      ` on conflict (id) do update set level = excluded.level, exp = excluded.exp, job_exp = excluded.job_exp, zeny_min = excluded.zeny_min, zeny_max = excluded.zeny_max, drops = excluded.drops;`,
  );
}
lines.push('');
for (const [id, sk] of Object.entries(data.skills)) {
  lines.push(
    `insert into public.skill_defs (id, cls, max_level) values (${q(id)}, ${q(sk.cls)}, ${sk.maxLevel})` +
      ` on conflict (id) do update set cls = excluded.cls, max_level = excluded.max_level;`,
  );
}
// Skills that left the game: drop them and give their points back (e.g. the old keyboardist skills).
const skillIds = Object.keys(data.skills).map(q).join(', ');
lines.push(
  '',
  '-- refund and remove skills that no longer exist',
  `update public.characters c set` +
    ` skill_points = c.skill_points + (select coalesce(sum(greatest(0, (e.value)::int)), 0) from jsonb_each_text(c.skills) e where e.key not in (${skillIds})),` +
    ` skills = (select coalesce(jsonb_object_agg(e.key, e.value), '{}'::jsonb) from jsonb_each(c.skills) e where e.key in (${skillIds}))` +
    ` where exists (select 1 from jsonb_object_keys(c.skills) k where k not in (${skillIds}));`,
  `delete from public.skill_defs where id not in (${skillIds});`,
);
writeFileSync(new URL('../supabase/migrations/0002_seed.sql', import.meta.url), lines.join('\n') + '\n');
console.log('wrote supabase/migrations/0002_seed.sql');

// One file to paste into the Supabase SQL Editor: schema + seed.
const init = readFileSync(new URL('../supabase/migrations/0001_init.sql', import.meta.url), 'utf8');
writeFileSync(
  new URL('../supabase/setup.sql', import.meta.url),
  '-- Music Land: paste this whole file into Supabase > SQL Editor and press Run.\n-- GENERATED by `npm run gen:seed`. Safe to run again after changing game data.\n\n' +
    init + '\n' + lines.join('\n') + '\n',
);
console.log('wrote supabase/setup.sql');
